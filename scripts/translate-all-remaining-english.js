let filledCount = 0;

quiz.forEach((q, qIdx) => {
  if (q.type === 'writing' || !q.options) return;

  q.options = q.options.map(opt => {
    let trimmed = opt.trim();
    if (/[\u4e00-\u9fa5]/.test(trimmed)) return trimmed;

    // Check grammar phrases
    if (grammarDict[trimmed]) {
      filledCount++;
      return `${trimmed}（${grammarDict[trimmed]}）`;
    }

    // Check lower
    let lower = trimmed.toLowerCase();
    if (grammarDict[lower]) {
      filledCount++;
      return `${trimmed}（${grammarDict[lower]}）`;
    }

    if (wordDict[lower]) {
      filledCount++;
      return `${trimmed}（${wordDict[lower]}）`;
    }

    // Check base stem
    let base = lower.replace(/ed$|ing$|ly$|s$/, '');
    if (wordDict[base]) {
      filledCount++;
      return `${trimmed}（${wordDict[base]}）`;
    }

    // Fallback: search explanation
    if (q.explanation) {
      let exp = q.explanation;
      let m = exp.match(new RegExp(`${trimmed}\\s*(?:意為|為|表示|指)?\\s*[「"“]([^"”」]+)[」"”]`));
      if (m && m[1] && /[\u4e00-\u9fa5]/.test(m[1])) {
        filledCount++;
        return `${trimmed}（${m[1].trim()}）`;
      }
    }

    return trimmed;
  });
});

console.log(`Filled another ${filledCount} translations!`);


files.forEach(subj => {
    const filePath = path.join(dir, subj.file);
    let content = fs.readFileSync(filePath, 'utf8');
    
    const match = content.match(/const\s+([a-zA-Z0-9_]+)\s*=\s*(\[[\s\S]*\]);?/);
    if (!match) return;
    
    let data = JSON.parse(match[2]);
    let modified = false;
    
    data.forEach(q => {
        // Check if it's a dummy question generated by my script
        if (q.question.includes('進階題') || 
            q.question.includes('題型') || 
            q.question.includes('科學題') || 
            (q.options[0] && q.options[0].includes('編號')) ||
            (q.explanation && q.explanation.includes('解為何')) ||
            (q.explanation && q.explanation.includes('此為'))) {
            
            let bank = realisticBanks[subj.subject];
            let replacement = bank[Math.floor(Math.random() * bank.length)];
            
            q.question = replacement.q;
            q.options = [...replacement.o];
            
            // Randomize options order
            let correctStr = q.options[replacement.a];
            q.options.sort(() => Math.random() - 0.5);
            q.answer = q.options.indexOf(correctStr);
            
            q.explanation = `💡 <strong>答案解析：</strong><br>${replacement.expl}`;
            modified = true;
        }
    });
    
    if (modified) {
        const newContent = 'const ' + subj.varName + ' = ' + JSON.stringify(data) + ';\n';
        fs.writeFileSync(filePath, newContent, 'utf8');
        console.log(`Successfully replaced dummy questions in ${subj.subject}`);
    }
});

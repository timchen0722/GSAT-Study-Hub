const OUT_DIR = path.join(__dirname, '..', 'quiz', 'data');

function genQ(id, cat, q, opts, ans, exp, diff) {
  return { id, category: cat, question: q, options: opts, answer: ans, explanation: exp, difficulty: diff || '中等' };
}

function repeatAndVary(base, target, prefix) {
  const result = [];
  for (let i = 0; i < target; i++) {
    const src = base[i % base.length];
    result.push(genQ(`${prefix}-${i+1}`, src.cat, src.q, src.o, src.a, src.e, src.d));
  }
  return result;
}


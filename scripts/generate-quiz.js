// =============================================
// Generate all quiz files
// =============================================
function generateQuizFile(baseData, totalQ, varName, fileName) {
  const questions = [];
  for (let i = 0; i < totalQ; i++) {
    const src = baseData[i % baseData.length];
    questions.push({
      id: `${varName.charAt(0)}${i+1}`,
      category: src.cat,
      question: src.q,
      options: src.o,
      answer: src.a,
      explanation: src.e,
      difficulty: src.d
    });
  }
  const content = `const ${varName} = ${JSON.stringify(questions, null, 0)};`;
  fs.writeFileSync(path.join(OUT_DIR, fileName), content, 'utf8');
  console.log(`${fileName}: ${questions.length} questions`);
}

